// Writes assets/content.js (every block in assets/blocks and every item in assets/items) and
// the module preload list in index.html.
// A file there whose default export is a definition (or a list of them) is registered by
// the game; files without a default export are helpers. Runs on npm start/dev and before
// every build, so adding content is just adding a file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const assets = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'assets');

function modules(dir) {
  return fs
    .readdirSync(path.join(assets, dir))
    .filter((f) => f.endsWith('.js') && f !== 'index.js')
    .filter((f) => /^export default/m.test(fs.readFileSync(path.join(assets, dir, f), 'utf8')))
    .sort((a, b) => (a === 'air.js' ? -1 : b === 'air.js' ? 1 : a.localeCompare(b)));
}

const blocks = modules('blocks');
const items = modules('items');
const name = (prefix, i) => `${prefix}${i}`;
const out = [
  '// Generated by build/scripts/gen-content.mjs: every file in assets/blocks and assets/items',
  '// with a default export. Don\'t edit; add or remove a file there and it updates itself.',
  ...blocks.map((f, i) => `import ${name('b', i)} from './blocks/${f}';`),
  ...items.map((f, i) => `import ${name('i', i)} from './items/${f}';`),
  '',
  `export const blocks = [${blocks.map((_, i) => name('b', i)).join(', ')}].flat();`,
  `export const items = [${items.map((_, i) => name('i', i)).join(', ')}].flat();`,
  ''
].join('\n');

const file = path.join(assets, 'content.js');
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) fs.writeFileSync(file, out);
console.log(`Content: ${blocks.length} block files, ${items.length} item files.`);

// Every module the game loads, listed in index.html so the browser fetches them all at once
// rather than finding each one only after the file importing it arrives.
const root = path.dirname(assets);
const seen = new Set();
const walk = (file) => {
  if (seen.has(file) || !fs.existsSync(file)) return;
  seen.add(file);
  const code = fs.readFileSync(file, 'utf8');
  for (const m of code.matchAll(/^\s*(?:import|export)\s[^'"]*?from\s*['"](\.{1,2}\/[^'"]+)['"]|^\s*import\s*['"](\.{1,2}\/[^'"]+)['"]/gm)) {
    walk(path.resolve(path.dirname(file), m[1] || m[2]));
  }
};
walk(path.join(root, 'src', 'script.js'));
const links = [...seen]
  .map((f) => path.relative(root, f).split(path.sep).join('/'))
  .sort()
  .map((f) => `  <link rel="modulepreload" href="${f}">`);
const htmlFile = path.join(root, 'index.html');
const html = fs.readFileSync(htmlFile, 'utf8');
const updated = html.replace(/(<!-- modules:start -->)[\s\S]*?(\s*<!-- modules:end -->)/, `$1\n${links.join('\n')}$2`);
if (updated !== html) fs.writeFileSync(htmlFile, updated);
console.log(`Preload: ${links.length} modules.`);
